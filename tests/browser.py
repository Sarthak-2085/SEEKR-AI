"""Run after npm run build. Requires Python Playwright and Chromium."""
import base64
import json
import os
import shutil
import subprocess
from playwright.sync_api import sync_playwright, expect

def exercise():
    bridge = subprocess.Popen(["node", "tests/worker-bridge.mjs"], stdin=subprocess.PIPE, stdout=subprocess.PIPE, text=True)
    def dispatch(route):
        req = route.request
        bridge.stdin.write(json.dumps(dict(url=req.url, method=req.method, headers=req.headers, body=req.post_data)) + "\n")
        bridge.stdin.flush()
        reply = json.loads(bridge.stdout.readline())
        route.fulfill(status=reply["status"], headers=reply["headers"], body=base64.b64decode(reply["body"]))
    try:
        with sync_playwright() as p:
            browser = p.chromium.launch(executable_path=os.environ.get("CHROMIUM_PATH") or shutil.which("chromium"), args=["--no-sandbox"])
            ctx = browser.new_context(viewport={"width": 1440, "height": 1000})
            ctx.route("https://seekr.test/**", dispatch)
            page = ctx.new_page()
            page.set_default_timeout(4500)
            errors = []
            page.on("pageerror", lambda e: errors.append(str(e)))
            page.goto("https://seekr.test/")
            expect(page.get_by_role("heading",name="Latest launches")).to_be_visible()
            if os.environ.get("SEEKR_SCREENSHOT"):
                page.screenshot(path=os.environ["SEEKR_SCREENSHOT"])
            for label in ["Launch Radar","AI Tool Finder","Compare","Technology Explained","Daily Briefing","Upcoming Radar","Collections","My Library","Saved Tools","Settings","Guest workspace","Overview"]:
                page.locator(".sidebar").get_by_role("link",name=label,exact=label!="Guest workspace").click()
                expect(page.locator("main h1").first).to_be_visible()
            page.locator(".hero input").fill("Hugging Face")
            page.locator(".hero input").press("Enter")
            expect(page.locator("main").get_by_role("link",name="Transformers",exact=True)).to_be_visible()
            page.locator(".sidebar").get_by_text("Launch Radar").click()
            page.get_by_label("Categories",exact=True).select_option("Coding Agents")
            expect(page.locator(".techCard")).to_have_count(3)
            page.get_by_role("link",name="Codex CLI",exact=True).click()
            expect(page.get_by_role("heading",name="Codex CLI",exact=True)).to_be_visible()
            page.get_by_role("button",name="Save Codex CLI",exact=True).click()
            page.get_by_role("button",name="Follow OpenAI",exact=True).click()
            page.reload()
            expect(page.get_by_role("button",name="Unsave Codex CLI",exact=True)).to_be_visible()
            expect(page.get_by_role("button",name="Following OpenAI",exact=True)).to_be_visible()
            page.locator(".sidebar").get_by_text("AI Tool Finder").click()
            page.get_by_text("Convert handwritten notes into editable text",exact=True).click()
            expect(page.get_by_role("link",name="TrOCR Handwritten",exact=True)).to_be_visible()
            page.locator(".sidebar").get_by_text("Compare",exact=True).click()
            page.get_by_label("Technology 1",exact=True).select_option("codex")
            page.get_by_label("Technology 2",exact=True).select_option("gemini-cli")
            expect(page.locator("thead th")).to_have_count(3)
            page.get_by_role("button",name="Add a third technology").click()
            page.get_by_label("Technology 3",exact=True).select_option("aider")
            expect(page.locator("thead th")).to_have_count(4)
            page.get_by_role("button",name="Save Codex CLI vs Gemini CLI vs Aider").click()
            page.locator(".sidebar").get_by_text("Collections",exact=True).click()
            page.get_by_role("button",name="New collection",exact=True).click()
            page.get_by_label("Collection name").fill("Project")
            page.get_by_role("button",name="Save collection").click()
            page.locator(".sidebar").get_by_text("My Library",exact=True).click()
            page.get_by_role("button",name="Organize Codex CLI",exact=True).click()
            page.get_by_role("checkbox",name="Project").check()
            page.get_by_role("button",name="Close dialog").click()
            page.locator(".sidebar").get_by_text("Collections",exact=True).click()
            page.locator("main").get_by_role("link",name="Project 1 saved items").click()
            expect(page.locator("main").get_by_text("Codex CLI",exact=True)).to_be_visible()
            page.get_by_role("button",name="Rename",exact=True).click()
            page.get_by_label("Collection name").fill("Research")
            page.get_by_role("button",name="Save collection").click()
            expect(page.get_by_role("heading",name="Research",exact=True)).to_be_visible()
            page.get_by_role("button",name="Delete",exact=True).click()
            page.get_by_role("button",name="Delete collection",exact=True).click()
            expect(page.get_by_role("heading",name="Create your first collection")).to_be_visible()
            page.locator(".sidebar").get_by_text("Daily Briefing",exact=True).click()
            page.locator(".newsLine a").first.click()
            expect(page.get_by_role("link",name="Read original announcement")).to_have_attribute("href", __import__("re").compile("^https://"))
            page.locator(".sidebar").get_by_text("Upcoming Radar",exact=True).click()
            expect(page.locator(".upcoming")).to_have_count(2)
            page.locator(".sidebar").get_by_text("Launch Radar",exact=True).click()
            page.get_by_label("Search records").fill("no-match-zzzzz")
            page.get_by_label("Search records").press("Enter")
            expect(page.get_by_role("heading",name="No results found")).to_be_visible()
            page.goto("https://seekr.test/")
            page.set_viewport_size({"width":390,"height":844})
            expect(page.get_by_role("button",name="Open navigation")).to_be_visible()
            assert page.evaluate("document.documentElement.scrollWidth <= window.innerWidth")
            page.get_by_role("button",name="Open navigation").click()
            page.locator(".sidebar").get_by_text("My Library",exact=True).click()
            expect(page.get_by_role("heading",name="My Library",exact=True)).to_be_visible()
            assert page.evaluate("document.documentElement.scrollWidth <= window.innerWidth")
            page.goto("https://seekr.test/technology/no-such-tech")
            expect(page.get_by_role("alert")).to_contain_text("Technology not found")
            ctx.set_extra_http_headers({"oai-authenticated-user-id":"editor-test","oai-authenticated-user-email":"curator@seekr.test"})
            page.goto("https://seekr.test/settings")
            expect(page.get_by_role("heading",name="Editorial review",exact=True)).to_be_visible()
            page.get_by_role("button",name="Review",exact=True).click()
            page.get_by_label("Why it matters",exact=True).fill("This confirms the editorial workflow.")
            page.get_by_role("button",name="Publish briefing",exact=True).click()
            expect(page.get_by_text("The review queue is empty.",exact=True)).to_be_visible()
            page.goto("https://seekr.test/briefings?q=Editorial%20test")
            expect(page.get_by_role("link",name="Editorial test briefing",exact=True)).to_be_visible()
            assert not errors, errors
            browser.close()
    finally:
        bridge.stdin.close()
        bridge.wait(timeout=10)
    print("PASS: navigation, global search, filters, detail, follows, bookmarks, Finder, two/three-way compare, collections, briefings, upcoming, empty/error states and mobile navigation.")

if __name__ == "__main__":
    exercise()
